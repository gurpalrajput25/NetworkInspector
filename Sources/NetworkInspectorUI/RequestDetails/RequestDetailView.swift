import SwiftUI
import NetworkInspectorCore
import NetworkInspectorIntegrations
import NetworkInspectorAnalytics

public enum RequestDetailTab: Int, CaseIterable, Identifiable {
    case overview = 0
    case aiSuggestions = 1
    case analytics = 2
    case request = 3
    case response = 4
    case curl = 5
    case multipart = 6

    public var id: Int { rawValue }

    public var title: String {
        switch self {
        case .overview: return "Overview"
        case .aiSuggestions: return "AI Suggestions"
        case .analytics: return "Analytics"
        case .request: return "Request"
        case .response: return "Response"
        case .curl: return "cURL"
        case .multipart: return "Multipart"
        }
    }

    public var iconName: String {
        switch self {
        case .overview: return "info.circle.fill"
        case .aiSuggestions: return "sparkles"
        case .analytics: return "chart.xyaxis.line"
        case .request: return "arrow.up.circle.fill"
        case .response: return "arrow.down.circle.fill"
        case .curl: return "terminal.fill"
        case .multipart: return "doc.on.doc.fill"
        }
    }
}

public struct RequestDetailView: View {
    public let transaction: NetworkTransaction
    @Environment(\.dismiss) private var dismiss
    @Environment(\.colorScheme) private var colorScheme

    @State private var selectedTab: Int = RequestDetailTab.overview.rawValue
    @State private var showingTeamsShare = false
    @State private var isLiveCurlMode = true

    public init(transaction: NetworkTransaction) {
        self.transaction = transaction
    }

    private var availableTabs: [RequestDetailTab] {
        var tabs: [RequestDetailTab] = [
            .overview,
            .aiSuggestions,
            .analytics,
            .request,
            .response,
            .curl
        ]
        if transaction.request.isMultipart || (transaction.multipartParts?.isEmpty == false) {
            tabs.append(.multipart)
        }
        return tabs
    }

    private var aiReport: APISuggestionReport {
        APISuggestionEngine.analyze(transaction: transaction)
    }

    public var body: some View {
        VStack(spacing: 0) {
            // Summary header
            headerSummaryView

            // Horizontally Scrollable Uncropped Tab Bar
            customTabBarView

            Divider()
                .overlay(Color.inspectorCardBorder)

            // Content Section
            ScrollView {
                VStack(spacing: 16) {
                    switch selectedTab {
                    case RequestDetailTab.overview.rawValue:
                        overviewSection
                    case RequestDetailTab.aiSuggestions.rawValue:
                        RequestAISuggestionsView(transaction: transaction) {
                            showingTeamsShare = true
                        }
                    case RequestDetailTab.analytics.rawValue:
                        RequestAnalyticsDetailView(transaction: transaction)
                    case RequestDetailTab.request.rawValue:
                        requestSection
                    case RequestDetailTab.response.rawValue:
                        responseSection
                    case RequestDetailTab.curl.rawValue:
                        curlSection
                    case RequestDetailTab.multipart.rawValue:
                        multipartSection
                    default:
                        EmptyView()
                    }
                }
                .padding()
            }
            .background(Color.inspectorBackground)
        }
        .background(Color.inspectorBackground)
        .navigationTitle(transaction.request.path)
        .inspectorNavigationTitleDisplayModeInline()
        .toolbar {
            ToolbarItem(placement: .cancellationAction) {
                Button("Done") { dismiss() }
            }
            ToolbarItem(placement: .primaryAction) {
                HStack(spacing: 12) {
                    Button {
                        showingTeamsShare = true
                    } label: {
                        Image(systemName: "paperplane.fill")
                            .font(.system(size: 14))
                    }

                    ShareLink(
                        item: DiagnosticReportBuilder.buildReport(for: transaction),
                        subject: Text("Network Report: \(transaction.request.path)"),
                        message: Text("Diagnostic network trace report generated by NetworkInspector.")
                    ) {
                        Image(systemName: "square.and.arrow.up")
                            .font(.system(size: 14))
                    }
                }
            }
        }
        .sheet(isPresented: $showingTeamsShare) {
            NavigationStack {
                TeamsShareView(transaction: transaction)
            }
        }
    }

    // MARK: - Horizontally Scrollable Tab Bar (Zero Text Cropping)

    private var customTabBarView: some View {
        ScrollViewReader { proxy in
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 8) {
                    ForEach(availableTabs) { tab in
                        let isSelected = (selectedTab == tab.rawValue)
                        Button {
                            withAnimation(.easeInOut(duration: 0.2)) {
                                selectedTab = tab.rawValue
                                proxy.scrollTo(tab.id, anchor: .center)
                            }
                        } label: {
                            HStack(spacing: 6) {
                                Image(systemName: tab.iconName)
                                    .font(.system(size: 12, weight: isSelected ? .bold : .semibold))

                                Text(tab.title)
                                    .font(.system(size: 13, weight: isSelected ? .bold : .medium))
                                    .fixedSize(horizontal: true, vertical: false)

                                // Dynamic badges
                                if tab == .aiSuggestions {
                                    let issuesCount = aiReport.spottedMistakes.count
                                    if issuesCount > 0 {
                                        Text("\(issuesCount)")
                                            .font(.system(size: 10, weight: .heavy))
                                            .padding(.horizontal, 6)
                                            .padding(.vertical, 1)
                                            .background(
                                                isSelected
                                                    ? Color.white.opacity(0.3)
                                                    : (aiReport.errorCount > 0 ? Color.red : Color.orange)
                                            )
                                            .foregroundColor(.white)
                                            .clipShape(Capsule())
                                    } else {
                                        Image(systemName: "checkmark")
                                            .font(.system(size: 9, weight: .bold))
                                            .foregroundColor(isSelected ? .white : .green)
                                    }
                                } else if tab == .response, let code = transaction.response?.statusCode {
                                    Text("\(code)")
                                        .font(.system(size: 10, weight: .bold, design: .monospaced))
                                        .padding(.horizontal, 5)
                                        .padding(.vertical, 1)
                                        .background(
                                            isSelected
                                                ? Color.white.opacity(0.25)
                                                : ((200...299).contains(code) ? Color.green.opacity(0.2) : Color.red.opacity(0.2))
                                        )
                                        .foregroundColor(
                                            isSelected
                                                ? .white
                                                : ((200...299).contains(code) ? .green : .red)
                                        )
                                        .clipShape(Capsule())
                                }
                            }
                            .padding(.horizontal, 14)
                            .padding(.vertical, 8)
                            .background(
                                isSelected
                                    ? Color.accentColor
                                    : Color.inspectorCardBackground
                            )
                            .foregroundColor(
                                isSelected
                                    ? .white
                                    : .primary
                            )
                            .overlay(
                                RoundedRectangle(cornerRadius: 10)
                                    .stroke(
                                        isSelected
                                            ? Color.clear
                                            : Color.inspectorCardBorder,
                                        lineWidth: 1
                                    )
                            )
                            .clipShape(RoundedRectangle(cornerRadius: 10))
                            .shadow(
                                color: isSelected
                                    ? Color.accentColor.opacity(colorScheme == .dark ? 0.4 : 0.22)
                                    : Color.clear,
                                radius: 4,
                                y: 2
                            )
                        }
                        .buttonStyle(.plain)
                        .id(tab.id)
                    }
                }
                .padding(.horizontal, 16)
                .padding(.vertical, 10)
            }
            .background(Color.inspectorSecondaryBackground)
        }
    }

    // MARK: - Subviews

    private var headerSummaryView: some View {
        HStack(alignment: .center, spacing: 12) {
            MethodBadgeView(method: transaction.request.rawMethod)
            StatusBadgeView(statusCode: transaction.response?.statusCode, isPending: transaction.status == .pending)

            VStack(alignment: .leading, spacing: 3) {
                Text(transaction.request.host)
                    .font(.caption.bold())
                    .foregroundColor(.secondary)
                    .lineLimit(1)
                Text(transaction.request.path)
                    .font(.system(size: 14, weight: .bold))
                    .foregroundColor(.primary)
                    .lineLimit(2)
                    .fixedSize(horizontal: false, vertical: true)
            }

            Spacer(minLength: 8)

            VStack(alignment: .trailing, spacing: 2) {
                Text(transaction.formattedDuration)
                    .font(.caption.bold().monospaced())
                    .foregroundColor(.primary)
                Text(transaction.formattedResponseSize)
                    .font(.caption2.monospaced())
                    .foregroundColor(.secondary)
            }
        }
        .padding(.horizontal, 16)
        .padding(.vertical, 12)
        .background(Color.inspectorSecondaryBackground)
    }

    private var overviewSection: some View {
        VStack(alignment: .leading, spacing: 14) {
            sectionCard(title: "General Information") {
                infoRow(title: "Full URL", value: transaction.request.url.absoluteString, allowCopy: true)
                infoRow(title: "HTTP Method", value: transaction.request.rawMethod)
                infoRow(title: "Status Code", value: "\(transaction.response?.statusCode ?? 0) (\(transaction.response?.statusDescription ?? "N/A"))")
                infoRow(title: "Duration", value: transaction.formattedDuration)
                infoRow(title: "Client Library", value: transaction.clientSource)
                infoRow(title: "Start Time", value: transaction.request.timestamp.formatted(date: .abbreviated, time: .standard))
                if let completedAt = transaction.response?.timestamp {
                    infoRow(title: "Completed At", value: completedAt.formatted(date: .abbreviated, time: .standard))
                }
            }

            if let metrics = transaction.metrics {
                sectionCard(title: "Timing & Waterfall") {
                    metricTimingRow(title: "DNS Lookup", duration: metrics.dnsDuration)
                    metricTimingRow(title: "TCP Connect", duration: metrics.connectDuration)
                    metricTimingRow(title: "TLS Handshake", duration: metrics.tlsDuration)
                    metricTimingRow(title: "Request Send", duration: metrics.requestDuration)
                    metricTimingRow(title: "Server Wait", duration: metrics.waitDuration)
                    metricTimingRow(title: "Response Download", duration: metrics.responseDuration)
                    metricTimingRow(title: "Total Duration", duration: metrics.totalDuration)
                    infoRow(title: "Connection Reused", value: metrics.isReusedConnection ? "Yes" : "No")
                    if let proto = metrics.protocolName {
                        infoRow(title: "Protocol", value: proto)
                    }
                }
            }

            if let err = transaction.error {
                sectionCard(title: "Error Details") {
                    infoRow(title: "Domain", value: err.domain)
                    infoRow(title: "Code", value: "\(err.code)")
                    infoRow(title: "Description", value: err.localizedDescription)
                    if let reason = err.failureReason {
                        infoRow(title: "Reason", value: reason)
                    }
                }
            }
        }
    }

    private var requestSection: some View {
        VStack(alignment: .leading, spacing: 16) {
            if !transaction.request.queryItems.isEmpty {
                sectionCard(title: "Query Parameters (\(transaction.request.queryItems.count))") {
                    HeaderListView(headers: transaction.request.queryItems)
                }
            }

            sectionCard(title: "Request Headers (\(transaction.request.headers.count))") {
                HeaderListView(headers: transaction.request.headers)
            }

            if let bodyStr = transaction.request.bodyString, !bodyStr.isEmpty {
                sectionCard(title: "Request Body (\(transaction.request.bodySize) bytes)") {
                    HStack {
                        Spacer()
                        CopyButton(textToCopy: bodyStr)
                    }
                    SyntaxHighlightedJSONView(jsonString: bodyStr)
                }
            }
        }
    }

    private var responseSection: some View {
        VStack(alignment: .leading, spacing: 16) {
            sectionCard(title: "Response Headers (\(transaction.response?.headers.count ?? 0))") {
                HeaderListView(headers: transaction.response?.headers ?? [:])
            }

            if let resBody = transaction.response?.bodyString, !resBody.isEmpty {
                sectionCard(title: "Response Body (\(transaction.response?.contentLength ?? 0) bytes)") {
                    HStack {
                        Spacer()
                        CopyButton(textToCopy: resBody)
                    }
                    SyntaxHighlightedJSONView(jsonString: resBody)
                }
            }
        }
    }

    private var curlSection: some View {
        let liveCurlCommand = transaction.generateCurl(maskTokens: false, singleLine: false)
        let singleLineLive = transaction.generateCurl(maskTokens: false, singleLine: true)
        let maskedCurlCommand = transaction.generateCurl(maskTokens: true, singleLine: false)
        let singleLineMasked = transaction.generateCurl(maskTokens: true, singleLine: true)

        return VStack(alignment: .leading, spacing: 16) {
            Picker("cURL Mode", selection: $isLiveCurlMode) {
                Text("⚡️ Live Token").tag(true)
                Text("🛡 Masked").tag(false)
            }
            .pickerStyle(.segmented)

            if isLiveCurlMode {
                // 1-Line Executable cURL
                VStack(alignment: .leading, spacing: 10) {
                    HStack {
                        VStack(alignment: .leading, spacing: 2) {
                            Text("1-Line cURL")
                                .font(.headline)
                            Text("Direct terminal or client execution with live unmasked token.")
                                .font(.caption2)
                                .foregroundColor(.secondary)
                        }
                        Spacer()
                        Button {
                            InspectorPasteboard.copy(singleLineLive)
                        } label: {
                            HStack(spacing: 4) {
                                Image(systemName: "bolt.fill")
                                Text("Copy 1-Line cURL")
                            }
                            .font(.caption.bold())
                            .padding(.horizontal, 10)
                            .padding(.vertical, 6)
                            .background(Color.accentColor)
                            .foregroundColor(.white)
                            .clipShape(Capsule())
                        }
                    }

                    ScrollView(.horizontal, showsIndicators: true) {
                        Text(singleLineLive)
                            .font(.system(size: 12, design: .monospaced))
                            .foregroundColor(.primary)
                            .padding(12)
                            .textSelection(.enabled)
                    }
                    .background(Color.inspectorCodeBackground)
                    .overlay(
                        RoundedRectangle(cornerRadius: 10)
                            .stroke(Color.inspectorCardBorder, lineWidth: 1)
                    )
                    .clipShape(RoundedRectangle(cornerRadius: 10))
                }

                // Multi-Line Formatted
                VStack(alignment: .leading, spacing: 10) {
                    HStack {
                        VStack(alignment: .leading, spacing: 2) {
                            Text("Multi-Line cURL")
                                .font(.subheadline.bold())
                            Text("Formatted with line breaks for Terminal execution.")
                                .font(.caption2)
                                .foregroundColor(.secondary)
                        }
                        Spacer()
                        CopyButton(textToCopy: liveCurlCommand)
                    }

                    ScrollView(.horizontal, showsIndicators: true) {
                        Text(liveCurlCommand)
                            .font(.system(size: 12, design: .monospaced))
                            .foregroundColor(.primary)
                            .padding(12)
                            .textSelection(.enabled)
                    }
                    .background(Color.inspectorCodeBackground)
                    .overlay(
                        RoundedRectangle(cornerRadius: 10)
                            .stroke(Color.inspectorCardBorder, lineWidth: 1)
                    )
                    .clipShape(RoundedRectangle(cornerRadius: 10))
                }

                HStack(spacing: 8) {
                    Image(systemName: "info.circle.fill")
                        .foregroundColor(.blue)
                    Text("Paste directly into your Terminal, HTTP client, or debugging script.")
                        .font(.caption)
                        .foregroundColor(.secondary)
                }
                .padding(10)
                .background(Color.blue.opacity(colorScheme == .dark ? 0.15 : 0.08))
                .overlay(
                    RoundedRectangle(cornerRadius: 8)
                        .stroke(Color.blue.opacity(0.2), lineWidth: 1)
                )
                .clipShape(RoundedRectangle(cornerRadius: 8))

                HStack(spacing: 6) {
                    Image(systemName: "exclamationmark.triangle.fill")
                        .font(.caption)
                        .foregroundColor(.orange)
                    Text("Contains live credentials. Handle with care.")
                        .font(.caption2)
                        .foregroundColor(.orange)
                }
            } else {
                // Masked 1-Line
                VStack(alignment: .leading, spacing: 10) {
                    HStack {
                        VStack(alignment: .leading, spacing: 2) {
                            Text("Masked 1-Line cURL")
                                .font(.headline)
                            Text("Tokens masked for safe developer sharing.")
                                .font(.caption2)
                                .foregroundColor(.secondary)
                        }
                        Spacer()
                        Button {
                            InspectorPasteboard.copy(singleLineMasked)
                        } label: {
                            HStack(spacing: 4) {
                                Image(systemName: "doc.on.doc")
                                Text("Copy 1-Line Masked")
                            }
                            .font(.caption.bold())
                            .padding(.horizontal, 10)
                            .padding(.vertical, 6)
                            .background(Color.inspectorMutedFill)
                            .foregroundColor(.primary)
                            .clipShape(Capsule())
                        }
                    }

                    ScrollView(.horizontal, showsIndicators: true) {
                        Text(singleLineMasked)
                            .font(.system(size: 12, design: .monospaced))
                            .foregroundColor(.primary)
                            .padding(12)
                            .textSelection(.enabled)
                    }
                    .background(Color.inspectorCodeBackground)
                    .overlay(
                        RoundedRectangle(cornerRadius: 10)
                            .stroke(Color.inspectorCardBorder, lineWidth: 1)
                    )
                    .clipShape(RoundedRectangle(cornerRadius: 10))
                }

                // Masked Multi-Line
                VStack(alignment: .leading, spacing: 10) {
                    HStack {
                        VStack(alignment: .leading, spacing: 2) {
                            Text("Masked Multi-Line cURL")
                                .font(.subheadline.bold())
                            Text("Formatted for bug reports and inspection.")
                                .font(.caption2)
                                .foregroundColor(.secondary)
                        }
                        Spacer()
                        CopyButton(textToCopy: maskedCurlCommand)
                    }

                    ScrollView(.horizontal, showsIndicators: true) {
                        Text(maskedCurlCommand)
                            .font(.system(size: 12, design: .monospaced))
                            .foregroundColor(.primary)
                            .padding(12)
                            .textSelection(.enabled)
                    }
                    .background(Color.inspectorCodeBackground)
                    .overlay(
                        RoundedRectangle(cornerRadius: 10)
                            .stroke(Color.inspectorCardBorder, lineWidth: 1)
                    )
                    .clipShape(RoundedRectangle(cornerRadius: 10))
                }
            }
        }
        .padding(14)
        .background(Color.inspectorSecondaryBackground)
        .overlay(
            RoundedRectangle(cornerRadius: 14)
                .stroke(Color.inspectorCardBorder, lineWidth: 1)
        )
        .clipShape(RoundedRectangle(cornerRadius: 14))
    }

    private var multipartSection: some View {
        VStack(alignment: .leading, spacing: 12) {
            Text("Multipart Form Data")
                .font(.headline)

            if let parts = transaction.multipartParts, !parts.isEmpty {
                ForEach(parts) { part in
                    VStack(alignment: .leading, spacing: 6) {
                        HStack {
                            Image(systemName: part.isFile ? "doc.fill" : "text.bubble.fill")
                                .foregroundColor(.accentColor)
                            Text(part.name)
                                .font(.subheadline.bold())
                            Spacer()
                            Text(part.formattedSize)
                                .font(.caption.monospaced())
                                .foregroundColor(.secondary)
                        }

                        if let fn = part.filename {
                            Text("Filename: \(fn)")
                                .font(.caption)
                                .foregroundColor(.secondary)
                        }
                        if let mime = part.mimeType {
                            Text("MIME: \(mime)")
                                .font(.caption2)
                                .foregroundColor(.secondary)
                        }
                    }
                    .padding(10)
                    .background(Color.inspectorCardBackground)
                    .overlay(
                        RoundedRectangle(cornerRadius: 10)
                            .stroke(Color.inspectorCardBorder, lineWidth: 1)
                    )
                    .clipShape(RoundedRectangle(cornerRadius: 10))
                }
            } else {
                Text("No multipart form-data parts parsed.")
                    .font(.subheadline)
                    .foregroundColor(.secondary)
            }
        }
        .padding(14)
        .background(Color.inspectorSecondaryBackground)
        .overlay(
            RoundedRectangle(cornerRadius: 14)
                .stroke(Color.inspectorCardBorder, lineWidth: 1)
        )
        .clipShape(RoundedRectangle(cornerRadius: 14))
    }

    // MARK: - Helpers

    private func sectionCard<Content: View>(title: String, @ViewBuilder content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 10) {
            Text(title)
                .font(.headline)
                .foregroundColor(.primary)
            content()
        }
        .padding(14)
        .background(Color.inspectorSecondaryBackground)
        .overlay(
            RoundedRectangle(cornerRadius: 14)
                .stroke(Color.inspectorCardBorder, lineWidth: 1)
        )
        .clipShape(RoundedRectangle(cornerRadius: 14))
    }

    private func infoRow(title: String, value: String, allowCopy: Bool = false) -> some View {
        HStack(alignment: .top, spacing: 10) {
            Text(title)
                .font(.system(size: 13, weight: .medium))
                .foregroundColor(.secondary)
                .frame(width: 105, alignment: .leading)
            Text(value)
                .font(.system(size: 13, design: .monospaced))
                .foregroundColor(.primary)
                .textSelection(.enabled)
                .fixedSize(horizontal: false, vertical: true)
                .frame(maxWidth: .infinity, alignment: .leading)
            if allowCopy {
                CopyButton(textToCopy: value)
            }
        }
        .padding(.vertical, 3)
    }

    private func metricTimingRow(title: String, duration: TimeInterval?) -> some View {
        HStack {
            Text(title)
                .font(.system(size: 13, weight: .medium))
                .foregroundColor(.secondary)
            Spacer()
            if let d = duration {
                Text(String(format: "%.1f ms", d * 1000))
                    .font(.system(size: 13, weight: .bold, design: .monospaced))
                    .foregroundColor(.primary)
            } else {
                Text("—")
                    .font(.system(size: 13, design: .monospaced))
                    .foregroundColor(.secondary)
            }
        }
        .padding(.vertical, 2)
    }
}
